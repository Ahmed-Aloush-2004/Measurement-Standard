-- 2) SECTIONS
-- ----------------------------------------------------------------------------
INSERT INTO sections (id, name, exam_type_id)
SELECT gen_random_uuid(), v.name, et.id
FROM (VALUES
  ('القدرات اللفظية'  , 1),
