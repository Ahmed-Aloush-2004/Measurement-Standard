  ('النحو'  , 1),
  ('الصرف'  , 2),
  ('البلاغة', 3),
  ('العروض' , 4),
  ('الإملاء', 5)
) AS v(name, ord)
JOIN exam_types et ON et.code = 'IRODORI'
WHERE NOT EXISTS (
  SELECT 1 FROM sections s
  WHERE s.exam_type_id = et.id AND s.name = v.name
);

